#!/usr/bin/env bash
# Auto-generate the Rust mirror of the C `client` struct layout from server.h.
#
# This is the "risky struct-layout mirror" done safely: instead of hand-copying
# the 110-field client struct into Rust (which drifts the instant someone edits
# the C struct), bindgen reads server.h with the SAME flags the build uses and
# emits byte-accurate Rust definitions. bindgen also emits layout_test functions
# that assert size/offset against the C ABI, so a drift is a compile/test
# failure, not silent UB.
#
# Run from the repo root:  rust/valkey_net/generate_bindings.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
SRC="$ROOT/src"
OUT="$ROOT/rust/valkey_net/src/generated/client_layout.rs"
mkdir -p "$(dirname "$OUT")"

# A tiny wrapper TU so bindgen has a single entry point; it just includes
# server.h with the build's defines.
WRAP="$(mktemp /tmp/vk_bindgen_XXXX.h)"
trap 'rm -f "$WRAP"' EXIT
cat > "$WRAP" <<'EOF'
#include "server.h"
EOF

# Clang args: mirror the build's includes and defines (from .make-settings
# PREV_FINAL_CFLAGS). jemalloc/zstd/backtrace are optional; include the common
# set so the preprocessor path matches a default build.
CLANG_ARGS=(
  -I"$SRC"
  -I"$ROOT/deps/libvalkey/include"
  -I"$ROOT/deps/linenoise"
  -I"$ROOT/deps/hdr_histogram"
  -I"$ROOT/deps/fpconv"
  -I"$ROOT/deps/fast_float"
  -I"$ROOT/deps/lz4"
  -I"$ROOT/deps/jemalloc/include"
  -D_GNU_SOURCE -D_REENTRANT
  -DUSE_RUST_NET -DUSE_RUST_IO_THREADS
  -DLUA_ENABLED -DSTATIC_LUA=1
  -DUSE_JEMALLOC
  -std=gnu11
)

bindgen "$WRAP" \
  --output "$OUT" \
  --allowlist-type '^client$' \
  --allowlist-type '^clientNet$' \
  --allowlist-type '^clientReplyBlock$' \
  --with-derive-default \
  --no-doc-comments \
  --raw-line '//! AUTO-GENERATED by rust/valkey_net/generate_bindings.sh -- DO NOT EDIT.' \
  --raw-line '//! Byte-accurate mirror of the C `client` struct and friends from server.h.' \
  --raw-line '//! bindgen emits layout assertions (size + field offsets) that fail the' \
  --raw-line '//! build if the C struct ever drifts from this mirror.' \
  --raw-line '#![allow(non_camel_case_types, non_snake_case, dead_code)]' \
  -- "${CLANG_ARGS[@]}"

echo "wrote $OUT ($(wc -l < "$OUT") lines)"
