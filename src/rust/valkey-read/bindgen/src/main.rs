/// Text between the `{` that follows `head` and its matching `}`.
fn body<'a>(src: &'a str, head: &str) -> Option<&'a str> {
    let start = src.find(head)? + head.len();
    let open = start + src[start..].find('{')?;
    let mut depth = 0;
    for (i, ch) in src[open..].char_indices() {
        match ch {
            '{' => depth += 1,
            '}' => {
                depth -= 1;
                if depth == 0 {
                    return Some(&src[open + 1..open + i]);
                }
            }
            _ => {}
        }
    }
    None
}

/// `pub name: Type,` pairs in declaration order.
fn fields(body: &str) -> Vec<(String, String)> {
    let flat: String = body.split_whitespace().collect::<Vec<_>>().join(" ");
    flat.split(',')
        .filter_map(|f| {
            let f = f.trim().strip_prefix("pub ")?;
            let (n, t) = f.split_once(':')?;
            Some((n.trim().to_string(), t.trim().to_string()))
        })
        .collect()
}

/// Layout asserts bindgen emitted: (type, field) -> offset, type -> size.
fn layout(src: &str) -> (BTreeMap<(String, String), u64>, BTreeMap<String, u64>) {
    let flat: String = src.split_whitespace().collect::<Vec<_>>().join(" ");
    let num = |s: &str| -> u64 {
        let i = s.find(" - ").unwrap() + 3;
        let j = i + s[i..].find("usize").unwrap();
        s[i..j].parse().unwrap()
    };
    let mut offs = BTreeMap::new();
    let mut sizes = BTreeMap::new();
    for (i, _) in flat
        .match_indices("\"Offset of field: ")
        .chain(flat.match_indices("\"Size of "))
    {
        let label = &flat[i + 1..i + 1 + flat[i + 1..].find('"').unwrap()];
        let rest = &flat[i + 1 + label.len()..];
        let rest = &rest[..rest.find(';').unwrap()];
        if let Some(tf) = label.strip_prefix("Offset of field: ") {
            let (t, f) = tf.split_once("::").unwrap();
            offs.insert((t.to_string(), f.to_string()), num(rest));
        } else if let Some(t) = label.strip_prefix("Size of ") {
            sizes.insert(t.to_string(), num(rest));
        }
    }
    for (i, _) in flat.match_indices("\"Alignment of ") {
        let label = &flat[i + 1..i + 1 + flat[i + 1..].find('"').unwrap()];
        let rest = &flat[i + 1 + label.len()..];
        let rest = &rest[..rest.find(';').unwrap()];
        sizes.insert(
            format!("align {}", &label["Alignment of ".len()..]),
            num(rest),
        );
    }
    (offs, sizes)
}

/// Named C fields of `ty` with offsets relative to `ty`, looking through
/// anonymous unions/structs the way C member access does.
fn flatten(
    src: &str,
    offs: &BTreeMap<(String, String), u64>,
    ty: &str,
    base: u64,
    sizes: &BTreeMap<String, u64>,
    out: &mut Vec<(String, u64)>,
) {
    let b = body(src, &format!("pub struct {ty} "))
        .or_else(|| body(src, &format!("pub union {ty} ")))
        .unwrap_or_else(|| panic!("no definition for {ty}"));
    let mut prev_end: u64 = 0;
    for (name, fty) in fields(b) {
        if name.starts_with("_bitfield") || name.starts_with("__bindgen_padding") {
            continue;
        }
        let off = match offs.get(&(ty.to_string(), name.clone())) {
            Some(o) => *o,
            // bindgen asserts no offset for anonymous members: place it
            // after the previous field, as C does.
            None if name.starts_with("__bindgen_anon_") => {
                let a = sizes[&format!("align {fty}")];
                prev_end.div_ceil(a) * a
            }
            None => panic!("no offset for {ty}::{name}"),
        };
        prev_end = off + type_size(src, sizes, &fty);
        if name.starts_with("__bindgen_anon_") {
            flatten(src, offs, &fty, base + off, sizes, out);
        } else {
            out.push((c_field(&name).to_string(), base + off));
        }
    }
}

/// Size of a field type on x86_64 (the only target the bindings support).
fn type_size(src: &str, sizes: &BTreeMap<String, u64>, t: &str) -> u64 {
    let t = t.trim();
    if t.starts_with('*') || t.starts_with("::std::option::Option<") {
        return 8;
    }
    if let Some(inner) = t.strip_prefix('[') {
        let (e, n) = inner.strip_suffix(']').unwrap().rsplit_once(';').unwrap();
        return type_size(src, sizes, e)
            * n.trim().trim_end_matches("usize").parse::<u64>().unwrap();
    }
    let base = t.rsplit("::").next().unwrap();
    match base {
        "u8" | "i8" | "bool" | "c_char" | "c_uchar" | "c_schar" => return 1,
        "u16" | "i16" | "c_short" | "c_ushort" => return 2,
        "u32" | "i32" | "f32" | "c_int" | "c_uint" => return 4,
        "u64" | "i64" | "f64" | "usize" | "isize" | "c_long" | "c_ulong" | "c_longlong"
        | "c_ulonglong" => return 8,
        _ => {}
    }
    if let Some(s) = sizes.get(base) {
        return *s;
    }
    let alias = format!("pub type {base} = ");
    let i = src
        .find(&alias)
        .unwrap_or_else(|| panic!("unknown type {t}"))
        + alias.len();
    type_size(src, sizes, &src[i..i + src[i..].find(';').unwrap()])
}

/// Bitfield accessors in `impl ty`: (C name, bit offset, width).
fn bitfields(src: &str, ty: &str) -> Vec<(String, u64, u64)> {
    let Some(b) = body(src, &format!("impl {ty} ")) else {
        return Vec::new();
    };
    let flat: String = b.split_whitespace().collect::<Vec<_>>().join(" ");
    let mut out = Vec::new();
    for part in flat.split("pub fn ").skip(1) {
        let name = &part[..part.find('(').unwrap()];
        if name.starts_with("set_")
            || name.starts_with("new_")
            || !part.starts_with(&format!("{name}(&self)"))
        {
            continue;
        }
        let Some(i) = part.find("_bitfield_") else {
            continue;
        };
        let unit = &part[i..];
        assert!(
            unit.starts_with("_bitfield_1.get("),
            "{ty}: only one bitfield unit is supported"
        );
        let args = &unit["_bitfield_1.get(".len()..unit.find(')').unwrap()];
        let (bit, width) = args.split_once(',').unwrap();
        let bit: u64 = bit.trim().trim_end_matches("usize").parse().unwrap();
        let width: u64 = width.trim().trim_end_matches("u8").parse().unwrap();
        out.push((c_field(name).to_string(), bit, width));
    }
    out
}

fn layout_h(src: &str) -> String {
    let (offs, sizes) = layout(src);
    let mut h = String::new();
    h.push_str(PREAMBLE);
    for (rty, cty) in CHECKED {
        let mut fl = Vec::new();
        flatten(src, &offs, rty, 0, &sizes, &mut fl);
        for (f, off) in fl {
            writeln!(h, "RUST_LAYOUT_OFFSET({cty}, {f}, {off});").unwrap();
        }
        let size = sizes[*rty];
        if SIZE_UNLESS_LOG_REQ_RES.contains(rty) {
            writeln!(
                h,
                "#ifndef LOG_REQ_RES\nRUST_LAYOUT_SIZE({cty}, {size});\n#endif"
            )
            .unwrap();
        } else {
            writeln!(h, "RUST_LAYOUT_SIZE({cty}, {size});").unwrap();
        }
        h.push('\n');
    }
    // src/sds.rs mirrors these by hand rather than through bindgen.
    for (t, w) in [
        ("sdshdr8", 1),
        ("sdshdr16", 2),
        ("sdshdr32", 4),
        ("sdshdr64", 8),
    ] {
        writeln!(h, "RUST_LAYOUT_OFFSET(struct {t}, len, 0);").unwrap();
        writeln!(h, "RUST_LAYOUT_OFFSET(struct {t}, alloc, {w});").unwrap();
        writeln!(h, "RUST_LAYOUT_OFFSET(struct {t}, flags, {});", 2 * w).unwrap();
        writeln!(h, "RUST_LAYOUT_OFFSET(struct {t}, buf, {});", 2 * w + 1).unwrap();
    }
    h.push_str("RUST_LAYOUT_OFFSET(struct sdshdr5, buf, 1);\n\n");
    h.push_str(BIT_CHECK);
    for (rty, cty) in CHECKED.iter().filter(|(t, _)| BITFIELDS_READ.contains(t)) {
        for (f, bit, _w) in bitfields(src, rty) {
            writeln!(h, "    RUST_LAYOUT_BIT({cty}, {f}, {bit});").unwrap();
        }
    }
    h.push_str("    return NULL;\n}\n\n#endif\n");
    h
}

fn main() {
    let argv: Vec<String> = env::args().collect();
    let sep = argv
        .iter()
        .position(|a| a == "--")
        .expect("usage: <bindings.rs> <layout.h> -- <clang args>");
    let (out_rs, out_h) = (&argv[1], &argv[2]);
    let b = builder(&argv[sep + 1..])
        .generate()
        .expect("bindgen failed on wrapper.h");
    let rs = format!(
        "// Generated by `make rust-bindings` (src/rust/valkey-read/bindgen). Do not edit.\n{b}"
    );
    fs::write(out_rs, &rs).expect("write bindings.rs");
    fs::write(out_h, layout_h(&rs)).expect("write layout.h");
}
